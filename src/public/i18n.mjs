let currentLang = 'en';

export function getLanguage(){
  return currentLang;
}

export function setLanguage(lang){
  currentLang = (lang === 'ru' ? 'ru' : 'en');
  document.documentElement.setAttribute('lang', currentLang);
  localStorage.setItem('skazitel-lang', currentLang);
  applyTranslations();
  return currentLang;
}

export function t(key){
  return translations[currentLang]?.[key] || translations['en']?.[key] || translations['ru']?.[key] || key;
}

export function initLanguage(){
  const saved = localStorage.getItem('skazitel-lang');
  setLanguage(saved || 'en');
}

export function applyTranslations(){
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if(el.tagName === 'INPUT' || el.tagName === 'TEXTAREA'){
      if(el.hasAttribute('placeholder')) el.placeholder = text;
    } else {
      const idChildren = el.querySelectorAll('[id]');
      if(idChildren.length > 0){
        const textNode = Array.from(el.childNodes).find(n => n.nodeType === 3);
        if(textNode) textNode.textContent = text + ' ';
      } else {
        el.innerHTML = text;
      }
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });

  const langLabel = document.getElementById('currentLangLabel');
  if(langLabel) langLabel.textContent = currentLang.toUpperCase();
}
